<div class="page about">
	<h1>◈ OpenWorld</h1>
	<p class="lede">A living creative ecosystem where humans and intelligent systems co-create — openly, visibly, and without containment.</p>

	<h2>Show anything, from anywhere</h2>
	<p>Your work stays where it lives: GitHub, YouTube, Spotify, Instagram, Drive, your own site. OpenWorld gives you modules to show it — players, galleries, timelines, credits, repos, and more.</p>

	<h2>GitHub first</h2>
	<p>We encourage keeping your creative material and deliverables in a GitHub repo, for every art form — even theater and dance. Commits are your process, releases are your premieres, forks are adaptations.</p>

	<h2>Anticontainment</h2>
	<ol>
		<li>Unfinished by design</li>
		<li>Open to mutation</li>
		<li>Hostile to enclosure</li>
		<li>Comfortable with ambiguity</li>
	</ol>
	<p class="muted">It does not scale like a startup. It spreads like a living idea. This is not final.</p>
